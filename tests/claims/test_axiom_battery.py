"""The axiom-battery: scientific_invention_axioms.md §9, run on this substrate.

The source document (P-4/P-5) demands leakage-controlled origination probes:
present the MECHANISM of an eponymous law under neutral vocabulary and ask
whether the system recovers its structure — the law itself never named in the
input. These tests do exactly that at the level CANDOR operates on, and the
expected pass/fail PROFILE is the point (C-16):

  * EX-1 Parkinson, EX-5 Peter (LC-2 rendered as streams): the driving variable
    is recovered as a gated condition with the right direction — PASS expected;
  * EX-7 Goodhart (LC-3): with the intervention marked as a `do:` key the
    regime-dependence is found BY NAME; unmarked, the collapse is still located
    as a DATE. But no machinery here predicts the decoupling before any
    post-intervention data exists — that boundary is asserted as expected
    behavior, because it is exactly T-1's claim about observational systems;
  * EX-8 / the EX-5 hazard (C-18 negative control): data generated by noise +
    regression to the mean must NOT yield the mechanism claim. Declining is the
    pass.

A profile deviating from this pattern falsifies or refines the document's
thesis (C-16) — which is why it lives in the claims suite, not conformance.
"""

from __future__ import annotations

import json
import random

import pytest

from candor.periphery import curiosity as C

from . import exemplars as X
from . import worlds as W
from .test_claims import seed_for

pytestmark = pytest.mark.claims


def _admitted_guards(m, fid):
    out = []
    for r in m.index.query(
            "SELECT body_json FROM candidates WHERE kind='guard' "
            "AND status='admitted' ORDER BY event_seq"):
        body = json.loads(r["body_json"])
        if body.get("target_fact") == fid:
            out.append(body)
    return out


def _build(pred, stream, stmt_type="frequency"):
    m = W.fresh_store("candor-battery-", actors=["tool:probe"])
    stmt = {"pred": pred, "args": ["probe"]}
    fid = W.admit(m, pred, ["probe"], stmt_type=stmt_type)
    W.feed(m, stmt, stream)
    m.run_gate()
    return m, stmt, fid


# ── EX-1 Parkinson (LC-2): originate the deadline-dependence ────────────────

def test_ex1_parkinson_deadline_dependence_originated():
    rng = random.Random(seed_for("ex1"))
    m, stmt, fid = _build("task_done_in_window", X.parkinson(240, rng))
    guards = _admitted_guards(m, fid)
    assert guards, "the deadline-dependence must surface as a gated condition"
    g = guards[0]
    assert g["conditioning_key"] == "deadline", \
        f"wrong frame chosen: {g['conditioning_key']}"
    assert g["body"]["guards"][0]["value"] == "short", \
        "direction must match the planted mechanism (short deadline → done)"
    m.close()


# ── EX-5 Peter (LC-2): originate the ceiling condition ──────────────────────

